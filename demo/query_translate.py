"""中文查询 → 英文 CLIP 检索短语翻译（主体/修饰词表组合）。

Immich 的 CLIP 模型（ViT-B-32__openai）以英文语料训练，中文查询的
文本 embedding 无语义区分度，smart search 的中文召回基本无效。
本模块把中文查询组合为**一条完整英文短语**（CLIP 对完整短语的
语义表达远好于逗号拼接的泛化提示词列表）：

    中文查询 --(词表最长匹配)--> 主体名词 + 修饰词
           --> "a photo of {主体} {介词短语}"

组合规则（对应汉语句法）：
    - 汉语名词短语中心语后置：**最后匹配到的主体名词为英文主体**，
      其余主体名词有介词形式（如 海边→at the beach）则作状语后置，
      否则以 "and ..." 并列。
    - 修饰词（颜色/表情/动作/风格）作为形容词插入主体冠词之后：
      "蓝色的车" → "a photo of a blue car"。
    - 景别词替换句式前缀："航拍的海边" → "an aerial photo of the beach"。

未命中（无主体名词）或不含中文时原样返回 (query, False)，由上层
附加降级警告；纯英文查询天然有效，直接透传。

词表规模由 tests/test_query_translate.py 断言保障（主体 ≥ 400、
修饰 ≥ 200），避免悄悄退化回覆盖不足的状态。
"""
