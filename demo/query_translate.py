# 景别/拍摄方式词表：{中文: 句式前缀}，替换默认的 "a photo of"。
# ---------------------------------------------------------------------------
_SHOT: dict[str, str] = {
    "特写": "a close-up photo of",
    "大特写": "an extreme close-up photo of",
    "全景": "a panoramic photo of",
    "近景": "a close-range photo of",
    "远景": "a wide distant view of",
    "航拍": "an aerial photo of",
    "俯拍": "a top-down photo of",
    "仰拍": "a low-angle photo of",
    "侧面": "a side-view photo of",
    "背影": "a photo of the back view of",
    "合影": "a group photo of",
    "自拍杆": "a selfie photo of",
}

# 组合上限：主体最多 3 个、修饰最多 3 个，防止 embedding 语义稀释。
_MAX_NOUNS = 3
_MAX_ADJ = 3

# 全表合并后按 key 长度降序（同长按字典序），贪心最长优先匹配。
_ENTRIES: list[tuple[str, str, Any]] = sorted(
    [(k, "noun", v) for k, v in _NOUNS.items()]
    + [(k, "adj", v) for k, v in _ADJ.items()]
    + [(k, "shot", v) for k, v in _SHOT.items()],
    key=lambda item: (-len(item[0]), item[0]),
)


def _match_all(query: str) -> list[tuple[int, str, str, Any]]:
    """最长优先贪心匹配全部词表，返回按出现位置排序的 (位置, key, 类型, 值)。"""
    matches: list[tuple[int, str, str, Any]] = []
    taken: list[tuple[int, int]] = []
    for key, kind, value in _ENTRIES:
        start = query.find(key)
        while start != -1:
            end = start + len(key)
            if not any(s < end and start < e for s, e in taken):
                matches.append((start, key, kind, value))
                taken.append((start, end))
                break
            start = query.find(key, start + 1)
    matches.sort(key=lambda m: m[0])
    return matches


def _insert_adjectives(noun_phrase: str, adjectives: list[str]) -> str:
    """把形容词插入名词短语冠词之后：a girl + smiling → a smiling girl。"""
    if not adjectives:
        return noun_phrase
    adj = " ".join(adjectives)
    for article in ("a ", "an ", "the ", "my "):
        if noun_phrase.startswith(article):
            return f"{article}{adj} {noun_phrase[len(article):]}"
    return f"{adj} {noun_phrase}"


def translate_query_detailed(query: str) -> dict[str, Any]:
    """详细翻译结果（供人工核对端点使用）。

    返回 {query, has_cjk, translated, english, nouns, adjectives, shot}，
    未翻译时 english 为 None。
    """
    original = query or ""
    q = original.strip()
    has_cjk = query_has_cjk(q)
    result: dict[str, Any] = {
        "query": original,
        "has_cjk": has_cjk,
        "translated": False,
        "english": None,
        "nouns": [],
        "adjectives": [],
        "shot": None,
    }
    if not q or not has_cjk:
        return result

    matches = _match_all(q)
    nouns = [(s, k, v) for s, k, kind, v in matches if kind == "noun"][:_MAX_NOUNS]
    adjectives = [(k, v) for s, k, kind, v in matches if kind == "adj"][:_MAX_ADJ]
    shot = next((v for _s, _k, kind, v in matches if kind == "shot"), None)

    # 无主体名词时不翻译（纯修饰词无法构成可靠语义），交由上层降级告警。
    if not nouns:
        return result

    result["nouns"] = [
        {"key": k, "phrase": v[0], "locative": v[1]} for _s, k, v in nouns
    ]
    result["adjectives"] = [{"key": k, "adjective": v} for k, v in adjectives]
    result["shot"] = shot

    # 汉语名词短语中心语后置：最后一个主体名词作为英文主体。
    primary_np = nouns[-1][2][0]
    others = [v for _s, _k, v in nouns[:-1]]

    composed = _insert_adjectives(primary_np, [v for _k, v in adjectives])
    prefix = shot or "a photo of"
    ands = [f"and {o[0]}" for o in others if not o[1]]
    locs = [o[1] for o in others if o[1]]

    result["english"] = " ".join([f"{prefix} {composed}", *ands, *locs])
    result["translated"] = True
    return result


def translate_query_for_clip(query: str) -> tuple[str, bool]:
    """把中文查询组合为一条英文 CLIP 检索短语。

    返回 (检索查询, 是否发生翻译)。不含中文/无主体命中时原样返回
    (query, False)，不影响主链路（上层负责附加降级警告）。
    """
    detail = translate_query_detailed(query)
    if detail["translated"]:
        return detail["english"], True
    return query, False


async def translate_query_for_search(query: str, settings: Any) -> tuple[str, bool, str]:
    """搜索链路入口：按配置调度翻译提供方，返回 (英文查询, 是否翻译, 提供方)。

    - translate_provider=dict（默认）：本地词表组合，零外部依赖。
    - translate_provider=huawei：华为云 NLP 机器翻译优先，
      未配置/失败/超时自动降级词表（返回 provider="dict"）。
    """
    provider = getattr(settings, "translate_provider", "dict")
    q = (query or "").strip()
    if provider == "huawei" and q and query_has_cjk(q):
        try:
            translated = await _huawei_translate(q, settings)
        except Exception as exc:
            logger.warning("华为云 NLP 翻译失败，降级为词表翻译: %s", exc)
        else:
            if translated:
                return translated, True, "huawei"
    english, ok = translate_query_for_clip(query)
    return english, ok, "dict"


async def _huawei_translate(text: str, settings: Any) -> str:
    """调用华为云 NLP 文本机器翻译（zh→en），失败由调用方降级。"""
    import json as _json

    import httpx

    from ..services.vision.huawei_signer import HuaweiCloudSigner

    ak = getattr(settings, "huawei_ak", "")
    sk_obj = getattr(settings, "huawei_sk", None)
    sk = sk_obj.get_secret_value() if sk_obj else ""
    project_id = getattr(settings, "huawei_project_id", "")
    if not ak or not sk or not project_id:
        raise RuntimeError("华为云 NLP 未配置 HUAWEI_AK/HUAWEI_SK/HUAWEI_PROJECT_ID")

    endpoint = getattr(
        settings, "huawei_nlp_endpoint", "https://nlp.cn-north-4.myhuaweicloud.com"
    ).rstrip("/")
    url = f"{endpoint}/v1/{project_id}/machine-translation/text-translation"
    body = _json.dumps({"text": text[:500], "from": "zh", "to": "en"}, ensure_ascii=False)
    signer = HuaweiCloudSigner(ak, sk)
    headers = signer.sign("POST", url, {"content-type": "application/json"}, body)
    timeout = getattr(settings, "translate_timeout_seconds", 3.0)
    async with httpx.AsyncClient(timeout=timeout) as client:
        resp = await client.post(
            url, content=body.encode("utf-8"), headers=headers
        )
        resp.raise_for_status()
        data = resp.json()
    return str(data.get("translated_text") or "").strip()
